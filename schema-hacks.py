def knowledge(term, key, default=None):
    return SCHEMA_KNOWLEDGE.get(term, {}).get(key, default)


def status_points(status):
    if status == "Documented rich result":
        return 35
    if status == "Documented structured data feature":
        return 25
    if status == "Related to documented Article markup":
        return 22
    if status == "Related to documented Review/Product markup":
        return 25
    if status == "Required/related property type for Product":
        return 25
    if status == "Limited / reduced visibility":
        return 8
    if status == "Not a standalone rich result":
        return 5
    return 0


def bias_penalty(bias):
    if bias == "High":
        return 15
    if bias == "Medium":
        return 8
    if bias == "Low":
        return 0
    return 4


def classify_opportunity(row):
    if row["site_status"] == "Detected":
        if row["priority_score"] >= 60:
            return "Audit quality"
        return "Monitor"

    if row["google_documented"] and row["niche_relevant"] and row["adoption_tier"] <= 3:
        return "Hidden gap"
    if row["google_documented"] and row["niche_relevant"] and row["adoption_tier"] >= 4:
        return "Core missing schema"
    if row["google_status"] == "Limited / reduced visibility":
        return "Use cautiously"
    if row["google_documented"] and not row["niche_relevant"]:
        return "Documented, weak niche fit"
    if (not row["google_documented"]) and row["niche_relevant"]:
        return "Semantic opportunity"
    if row["adoption_tier"] >= 4 and row["cms_bias"] == "High":
        return "Popular / plugin-driven"
    return "Low priority"


def priority_label(score):
    if score >= 80:
        return "Critical"
    if score >= 60:
        return "High"
    if score >= 40:
        return "Medium"
    return "Low"


def enrich(df, niche, detected_terms):
    df = df.copy()
    playbook = set(NICHE_PLAYBOOKS.get(niche, []))
    detected = set(detected_terms)

    df["google_feature"] = df["term"].apply(lambda t: knowledge(t, "google_feature", "No Google mapping"))
    df["google_status"] = df["term"].apply(lambda t: knowledge(t, "google_status", "Not mapped"))
    df["seo_value"] = df["term"].apply(lambda t: knowledge(t, "value", 1))
    df["cms_bias"] = df["term"].apply(lambda t: knowledge(t, "bias", "Unknown"))
    df["why_it_matters"] = df["term"].apply(lambda t: knowledge(t, "why", "No curated note yet. Treat as raw Schema.org adoption data."))
    df["audit_focus"] = df["term"].apply(lambda t: knowledge(t, "audit", "Validate against visible content, Google guidelines, and business relevance."))
    df["niche_relevant"] = df["term"].apply(lambda t: niche in knowledge(t, "industries", []))
    df["in_niche_playbook"] = df["term"].apply(lambda t: t in playbook)
    df["site_status"] = df["term"].apply(lambda t: "Detected" if t in detected else "Missing")

    df["google_documented"] = df["google_status"].apply(
        lambda x: (
            "Documented rich result" in x
            or "Documented structured data feature" in x
            or "Related to documented" in x
            or "Required/related" in x
        )
    )

    df["priority_score"] = (
        df["adoption_tier"] * 8
        + df["seo_value"] * 8
        + df["google_status"].apply(status_points)
        + df["niche_relevant"].astype(int) * 15
        + df["in_niche_playbook"].astype(int) * 15
        - df["cms_bias"].apply(bias_penalty)
    ).clip(lower=0, upper=100).round(0).astype(int)

    df["priority"] = df["priority_score"].apply(priority_label)
    df["recommendation_bucket"] = df.apply(classify_opportunity, axis=1)

    return df


def make_recommendation(row, niche):
    term = row["term"]
    status = row["site_status"]

    if status == "Detected":
        action = "Audit implementation quality, validation errors, duplicate nodes, required/recommended properties, and alignment with visible page content."
    elif row["recommendation_bucket"] in ["Hidden gap", "Core missing schema"]:
        action = "Prioritize implementation on the relevant template. This schema has clear niche/search relevance and is currently missing from the provided detected list."
    elif row["recommendation_bucket"] == "Semantic opportunity":
        action = "Consider implementation if the site has a real entity/template need. Do not position it as a direct rich-result lever."
    elif row["recommendation_bucket"] == "Use cautiously":
        action = "Use only when it truly matches visible page content. Avoid treating it as a high-impact rich-result tactic."
    else:
        action = "Keep as a lower-priority investigation item unless there is a strong business/template reason."

    return f"""### {term}

**Status:** {row['site_status']}  
**Priority:** {row['priority']} ({row['priority_score']}/100)  
**Opportunity bucket:** {row['recommendation_bucket']}  
**Adoption:** {row['bucket']}  
**Google feature:** {row['google_feature']}  
**Google status:** {row['google_status']}  
**Niche relevance for {niche}:** {'Yes' if row['niche_relevant'] else 'No'}  
**CMS/plugin bias:** {row['cms_bias']}

**Why it matters:**  
{row['why_it_matters']}

**Recommended action:**  
{action}

**Audit focus:**  
{row['audit_focus']}
"""


