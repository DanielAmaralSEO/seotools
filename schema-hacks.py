def normalize_bucket(value):
    value = str(value).strip()
    replacements = {
        "0-1K": "< 1K",
        "0 - 1K": "< 1K",
        "<1K": "< 1K",
        "< 1k": "< 1K",
        "1k-10k": "1K - 10K",
        "1K-10K": "1K - 10K",
        "10K-100K": "10K - 100K",
        "100K-1M": "100K - 1M",
        "1M+": "> 1M",
        ">1M": "> 1M",
    }
    return replacements.get(value, value)


def normalize_term(value):
    value = str(value).strip()
    value = value.replace("http://schema.org/", "")
    value = value.replace("https://schema.org/", "")
    value = value.replace("schema:", "")
    value = value.split("/")[-1]
    return value.strip()


def parse_detected_schemas(text):
    if not text:
        return []
    for sep in ["\n", ";", "|", "\t"]:
        text = text.replace(sep, ",")
    return sorted(set([normalize_term(x) for x in text.split(",") if normalize_term(x)]))


@st.cache_data(ttl=3600)
def get_csv_files():
    try:
        response = requests.get(GITHUB_API_URL, timeout=20)
        if response.status_code != 200:
            return [FALLBACK_FILE]
        items = response.json()
        csv_files = sorted([item.get("name") for item in items if item.get("name", "").endswith(".csv")])
        return csv_files if csv_files else [FALLBACK_FILE]
    except Exception:
        return [FALLBACK_FILE]


@st.cache_data(ttl=3600)
def load_month(file_name):
    url = RAW_BASE_URL + file_name
    response = requests.get(url, timeout=30)
    if response.status_code != 200:
        raise RuntimeError(f"Could not download {file_name}")

    raw = pd.read_csv(StringIO(response.text))
    required_cols = ["Class", "Name", "Domain Bucket"]
    missing = [c for c in required_cols if c not in raw.columns]
    if missing:
        raise RuntimeError(f"Missing required columns: {missing}")

    df = raw.copy()
    df["month"] = file_name.replace(".csv", "")
    df["term_type"] = df["Class"].astype(str).str.strip()
    df["term"] = df["Name"].apply(normalize_term)
    df["bucket"] = df["Domain Bucket"].apply(normalize_bucket)
    df["adoption_tier"] = df["bucket"].map(BUCKET_ORDER).fillna(0).astype(int)
    df["estimated_domains_midpoint"] = df["bucket"].map(BUCKET_MIDPOINT).fillna(0).astype(int)

    return df[["month", "term_type", "term", "bucket", "adoption_tier", "estimated_domains_midpoint"]]


@st.cache_data(ttl=3600)
def load_all_data():
    files = get_csv_files()
    frames = []
    skipped = []
    for file in files:
        try:
            frames.append(load_month(file))
        except Exception as exc:
            skipped.append((file, str(exc)))

    if not frames:
        st.error("No Schema.org public usage statistics CSV could be loaded.")
        st.stop()

    return pd.concat(frames, ignore_index=True), files, skipped

